package com.gomysearch.app;

import android.Manifest;
import android.app.Activity;
import android.os.Bundle;
import android.content.pm.PackageManager;
import android.location.Location;
import android.location.LocationListener;
import android.location.LocationManager;
import android.content.Context;
import android.widget.Button;
import android.widget.EditText;
import android.widget.LinearLayout;
import android.widget.TextView;
import android.widget.Toast;
import android.view.Gravity;
import android.graphics.Typeface;
import android.graphics.Color;
import android.os.Build;
import android.util.TypedValue;
import java.net.HttpURLConnection;
import java.net.URL;
import java.io.OutputStream;
import java.nio.charset.StandardCharsets;
import java.text.SimpleDateFormat;
import java.util.Date;
import java.util.Locale;
import java.util.TimeZone;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;

/*
 * Minimal transparent location-reporting client for the owner's enrolled device.
 * Enter your deployed GomySearch web root and the one-time credential generated by the dashboard.
 * This starter reports only while the app is open; reliable background reporting
 * requires a foreground service, notification, battery-policy handling and testing.
 */
public class MainActivity extends Activity {
    private LocationManager locationManager;
    private LocationListener activeListener;
    private TextView status;
    private EditText serverField, tokenField;
    private final ExecutorService executor = Executors.newSingleThreadExecutor();

    @Override public void onCreate(Bundle state) {
        super.onCreate(state);
        LinearLayout root = new LinearLayout(this);
        root.setOrientation(LinearLayout.VERTICAL);
        root.setPadding(dp(24), dp(48), dp(24), dp(24));
        root.setBackgroundColor(Color.rgb(245,247,243));
        TextView title = new TextView(this);
        title.setText("GomySearch");
        title.setTextSize(TypedValue.COMPLEX_UNIT_SP, 30);
        title.setTypeface(Typeface.DEFAULT, Typeface.BOLD);
        title.setTextColor(Color.rgb(23,32,30));
        root.addView(title);
        serverField = new EditText(this); serverField.setSingleLine(true); serverField.setHint("Server URL, e.g. https://example.com/gomysearch");
        serverField.setText(getPreferences(MODE_PRIVATE).getString("server", ""));
        LinearLayout.LayoutParams fp = new LinearLayout.LayoutParams(-1,-2); fp.topMargin=dp(22); root.addView(serverField,fp);
        tokenField = new EditText(this); tokenField.setSingleLine(true); tokenField.setHint("One-time device credential from GomySearch");
        tokenField.setText(getPreferences(MODE_PRIVATE).getString("token", ""));
        root.addView(tokenField);
        TextView intro = new TextView(this);
        intro.setText("Owner-authorized device location reporting");
        intro.setTextSize(15); intro.setTextColor(Color.DKGRAY);
        LinearLayout.LayoutParams ip = new LinearLayout.LayoutParams(-1,-2); ip.topMargin=dp(8); root.addView(intro,ip);
        status = new TextView(this);
        status.setText("Location reporting is off until you grant permission and start it.");
        status.setTextSize(14); status.setTextColor(Color.DKGRAY);
        LinearLayout.LayoutParams sp = new LinearLayout.LayoutParams(-1,-2); sp.topMargin=dp(28); root.addView(status,sp);
        Button start = new Button(this); start.setText("Enable location reporting");
        LinearLayout.LayoutParams bp = new LinearLayout.LayoutParams(-1,-2); bp.topMargin=dp(18); root.addView(start,bp);
        TextView disclaimer = new TextView(this);
        disclaimer.setText("Location requires permission and connectivity. This app does not prevent factory resets or firmware flashing. Configure the server URL and one-time device credential before use.");
        disclaimer.setTextSize(12); disclaimer.setTextColor(Color.GRAY);
        LinearLayout.LayoutParams dp = new LinearLayout.LayoutParams(-1,-2); dp.topMargin=dp(24); root.addView(disclaimer,dp);
        setContentView(root);
        start.setOnClickListener(v -> { getPreferences(MODE_PRIVATE).edit().putString("server", serverField.getText().toString().trim()).putString("token", tokenField.getText().toString().trim()).apply(); requestLocation(); });
    }
    private int dp(int v){ return (int)(v*getResources().getDisplayMetrics().density); }
    private void requestLocation() {
        if (Build.VERSION.SDK_INT >= 23 && checkSelfPermission(Manifest.permission.ACCESS_FINE_LOCATION)!=PackageManager.PERMISSION_GRANTED) {
            requestPermissions(new String[]{Manifest.permission.ACCESS_FINE_LOCATION,Manifest.permission.ACCESS_COARSE_LOCATION}, 100);
            return;
        }
        beginUpdates();
    }
    @Override public void onRequestPermissionsResult(int requestCode,String[] permissions,int[] results) {
        super.onRequestPermissionsResult(requestCode,permissions,results);
        if(requestCode==100 && results.length>0 && results[0]==PackageManager.PERMISSION_GRANTED) beginUpdates();
        else status.setText("Location permission was not granted.");
    }
    private void beginUpdates() {
        try {
            locationManager=(LocationManager)getSystemService(Context.LOCATION_SERVICE);
            Location last=null;
            if(checkSelfPermission(Manifest.permission.ACCESS_FINE_LOCATION)==PackageManager.PERMISSION_GRANTED) {
                last=locationManager.getLastKnownLocation(LocationManager.GPS_PROVIDER);
                activeListener = new LocationListener(){
                    @Override public void onLocationChanged(Location loc){ sendLocation(loc); }
                    @Override public void onProviderEnabled(String provider){}
                    @Override public void onProviderDisabled(String provider){ runOnUiThread(()->status.setText("GPS provider is disabled.")); }
                };
                locationManager.requestLocationUpdates(LocationManager.GPS_PROVIDER,60000,25,activeListener);
            }
            if(last!=null) sendLocation(last);
            status.setText("Location reporting is active while this app is running. Keep the app and device permissions enabled.");
        } catch(SecurityException e){ status.setText("Location permission is required."); }
        catch(Exception e){ status.setText("Unable to start location updates on this device."); }
    }
    private void sendLocation(Location l) {
        String server=getPreferences(MODE_PRIVATE).getString("server", "");
        String token=getPreferences(MODE_PRIVATE).getString("token", "");
        if(server.isEmpty() || token.length()!=64) { runOnUiThread(()->status.setText("Enter your GomySearch server URL and 64-character device credential.")); return; }
        executor.execute(()->{
            HttpURLConnection c=null;
            try {
                URL licenseUrl=new URL(server.replaceAll("/$", "")+"/api/license.php");
                HttpURLConnection lic=(HttpURLConnection)licenseUrl.openConnection();
                lic.setRequestMethod("POST"); lic.setConnectTimeout(12000); lic.setReadTimeout(12000);
                lic.setRequestProperty("Authorization","Bearer "+token);
                int licCode=lic.getResponseCode(); lic.disconnect();
                if(licCode!=200) { runOnUiThread(()->status.setText(licCode==402?"Payment required: activate your GomySearch account.":"Device licence check failed (HTTP "+licCode+").")); return; }
                c=(HttpURLConnection)new URL(server.replaceAll("/$", "")+"/api/location.php").openConnection();
                c.setRequestMethod("POST"); c.setConnectTimeout(12000); c.setReadTimeout(12000);
                c.setDoOutput(true); c.setRequestProperty("Content-Type","application/json");
                c.setRequestProperty("Authorization","Bearer "+token);
                SimpleDateFormat sdf=new SimpleDateFormat("yyyy-MM-dd'T'HH:mm:ss'Z'",Locale.US); sdf.setTimeZone(TimeZone.getTimeZone("UTC"));
                String json=String.format(Locale.US,"{\"latitude\":%.7f,\"longitude\":%.7f,\"accuracy_m\":%.2f,\"recorded_at\":\"%s\"}",l.getLatitude(),l.getLongitude(),l.getAccuracy(),sdf.format(new Date(l.getTime())));
                try(OutputStream os=c.getOutputStream()){os.write(json.getBytes(StandardCharsets.UTF_8));}
                int code=c.getResponseCode();
                runOnUiThread(()->status.setText(code>=200&&code<300?"Secure location report sent.":"Server rejected report (HTTP "+code+")."));
            } catch(Exception e){runOnUiThread(()->status.setText("Report failed. Check internet and server configuration."));}
            finally{if(c!=null)c.disconnect();}
        });
    }
    @Override protected void onDestroy(){super.onDestroy();executor.shutdownNow();if(locationManager!=null && activeListener!=null)locationManager.removeUpdates(activeListener);}
}
